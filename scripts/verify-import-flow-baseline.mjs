import assert from 'node:assert/strict';
import { existsSync, mkdirSync, writeFileSync } from 'node:fs';
import { resolve, join } from 'node:path';
import { pathToFileURL } from 'node:url';
import { createFromSource, loadConfig, resolveServer } from '../dist/src/config.js';
const out=resolve(process.argv[2]??'runs/import-flow-comparison-20261002');
if(existsSync(out))throw new Error('Choose a new evidence directory.');
mkdirSync(join(out,'runtime'),{recursive:true});mkdirSync(join(out,'source'));mkdirSync(join(out,'destination'));
const source=join(out,'source/mcp.json');
writeFileSync(source,JSON.stringify({mcpServers:{one:{command:process.execPath,args:['./server.cjs','./literal-value'],cwd:'../runtime',env:{API_KEY:'${SHARED_TOKEN}'}}}}));
const prior=await import(pathToFileURL(resolve('runs/configuration-third-clean-install-20261002/dist/src/config.js')).href);
const oldPath=join(out,'destination/old.yaml'),newPath=join(out,'destination/new.yaml');
prior.createFromSource(source,oldPath);
const summary=createFromSource(source,newPath);
const before=prior.resolveServer(prior.loadConfig(oldPath),oldPath),after=resolveServer(loadConfig(newPath),newPath);
assert.equal(before.env.API_KEY,'${API_KEY}');assert.equal(after.env.API_KEY,'${SHARED_TOKEN}');
assert.notDeepEqual(before.args,after.args);assert.deepEqual(after.args,['./server.cjs','./literal-value']);assert.equal(before.cwd,after.cwd);
writeFileSync(join(out,'results.json'),JSON.stringify({modelRequests:0,startedServices:false,before:{envReference:before.env.API_KEY,args:before.args,cwd:before.cwd},after:{envReference:after.env.API_KEY,args:after.args,cwd:after.cwd},requiredEnvironment:summary.requiredEnvironment,conclusion:'Preserve the original variable reference and literal argv; anchor cwd independently of output directory.'},null,2));
console.log('PASS: prior/current synthetic import comparison; no services or models started.');
